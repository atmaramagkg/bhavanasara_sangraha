def main():
    if len(sys.argv) < 2:
        print("usage: add_ru_danda_descriptions.py <input.sqlite> [<input.sqlite> ...]")
        sys.exit(1)

    for db_path in sys.argv[1:]:
        con = sqlite3.connect(db_path)
        cur = con.cursor()

        for n in range(1, 61):
            key = f"period.danda.{n}.desc"
            cur.execute(
                "INSERT OR REPLACE INTO translations (language_id, translation_key, translated_text)"
                " VALUES (2, ?, ?)",
                (key, DANDA_DESCRIPTIONS_RU[n - 1]),
            )

        con.commit()
        n_ru = cur.execute(
            "SELECT COUNT(*) FROM translations WHERE language_id = 2"
        ).fetchone()[0]
        con.close()
        print(f"{db_path}: {n_ru} ru translations present")


if __name__ == "__main__":
    main()
